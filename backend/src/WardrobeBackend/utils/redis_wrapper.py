from redis import RedisError
import redis.asyncio as redis
import json
from functools import wraps
from typing import Callable, Optional
from src.WardrobeBackend.utils.redis_pool import generate_client

redis_client: redis.Redis = None

# Used to avoid Redis being unable to find the keys due to typing mistakes, update the list if 
# redis caching is added to more parts of the application
ALLOWED_PREFIXES = ["outfits", "outfits_saved", "outfits_items", "outfits_friends", "items", "profiles"
                    "users", "notifications", "friends"]

def cache(
    ttl : int = 300, 
    prefix : str = "cache", 
    key_builder : Optional[Callable] = None, 
):
    """ Decorator to cache the result of the function or retrieve it

    Args:
        ttl (int, optional): Time until cached data is invalidated. Defaults to 300 seconds.
        prefix (str, optional): Fixed label for the cache key. Defaults to "cache".
        key_builder (Optional[Callable], optional): Custom function to generate the 
        cache key. Defaults to None.
        redis_client (redis.Redis) : Redis database client to connect to. Defaults to a dependancy 
        that yields a client from a Redis connection pool
    """
    if prefix not in ALLOWED_PREFIXES:
         raise ValueError(f"Attention! The given prefix '{prefix}' is not in the list of allowed ones.")
    
    def decorator(func : Callable):
        @wraps(func)
        async def wrapper(*args, **kwargs):
            # Check that redis is available
            redis_client = generate_client()
            if not redis_client:
                return func(*args, **kwargs)
                
            # Build the cache key
            cache_parts = ["cache", prefix]
            if key_builder:
                custom_key = key_builder(*args, **kwargs)
                cache_parts.append(custom_key)
            else:
                for arg in args:
                    cache_parts.append(str(arg))

                for k, v in sorted(kwargs.items()):
                    cache_parts.append(f"{k}={v}")
            cache_key = ":".join(cache_parts)

            # Try to get the result from cache
            try:
                result = await redis_client.get(cache_key)
                if result:
                    return json.loads(result)
            except (redis.ConnectionError, json.JSONDecodeError):
                print(f"Cache read failed for key {cache_key}")
                pass

            # Call the actual function
            result = func(*args, **kwargs)

            # Cache the result
            try:
                await redis_client.set(cache_key, result, ex = ttl)
            except redis.ConnectionError:
                print(f"Cached write failed for key {cache_key}")
                pass
            return result
        return wrapper
    return decorator

# Invalidate a cache key value pair that has been created using a single prefix and a suffix with
# the latter generated by one of the key builders in the redis_client.py class
async def invalidate_with_builder(prefix : str, suffixes : str | list[str]):
    if prefix not in ALLOWED_PREFIXES:
        raise ValueError(f"Attention! The given prefix '{prefix}' is not in the list of allowed ones.")
    keys = [f"cache:{prefix}:{suffix}" for suffix in suffixes]
    try:
        await generate_client().delete(keys)
    except RedisError:
        print(f"Unable to invalidate keys : {keys}")

# Safer approach than the key command by fetching keys in batches using a cursor.
# The number of keys detected via the search is controlled via the count parameter
async def invalidate_with_pattern(pattern : str):
    redis_client = await generate_client()
    cursor = "0"

    while cursor != 0:
        # Scan for keys matching the pattern (non-blocking)
        try:
            cursor, keys = redis_client.scan(cursor = cursor, match = pattern, count = 1000)
        except RedisError:
            print(f"Failed to scan keys for pattern {pattern}")
        if keys:
            for key in keys:
                try:
                    redis_client.delete(key)
                except RedisError:
                    print(f"Failed to delete key {key}")



